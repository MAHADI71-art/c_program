#include <stdio.h>

int main(void)
{
    int n = 5;
    int i = 1;
 //যদি 'i' এর মান আগেই দেওয়া আছে তাই লুপের মধ্যে না করলেও চলবে।
 //কোন অংশ বাদ দিতে চাইলে দিতে পারব কিন্তু সেমিকোলন অবশ্যই দিতে হবে।
    for(; i <= 10; i = i + 1)
    {
        printf("%d * %d = %d\n", n, i, n*i);
    }

    return 0;
}