#include <stdio.h>

int main(void)
{
    int a, b, c;//a-এর মান দেওয়া হয়নি
    for ( b = 1; b <= 3; b++)
    {
        if ( b != a)
        {/*b- এর মান  a-এর মানের সমান না হলেই ভেতেরের অংশে
            প্রোগ্রামটি ঢুকবে। */
         for (c = 1; c <= 3; c++)
         {
            if (c != a && c != b)
            {/*c- এর মান a-এর মানের সমান
                না হলে এবং c-এর মান b-এর মানের সমান না হলেই কেবল
                ভেতরের অংশে প্রোগ্রামটি ঢুকবে। */
              printf ("%d, %d, %d\n", a, b, c); 

            }
         }
        }
    }
    return 0;
}