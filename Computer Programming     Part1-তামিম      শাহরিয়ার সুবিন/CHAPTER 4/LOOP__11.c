#include <stdio.h>

int main(void)
{
    int n, m, i, j;

    scanf("%d", &n);

    for (i = 0;  i < n; i++)
    {
        scanf("%d", &m);

        for(j = 10; j <= m; j++)
        {
            if ( j % 11 == 0)
            {
                continue;
            }
            
            printf("%d\n", j);
        }
    }
    return 0;

}
/*
Start
   │
   ▼
n ইনপুট নাও
   │
   ▼
n বার লুপ চালাও
   │
   ▼
m ইনপুট নাও
   │
   ▼
j = 10
   │
   ▼
j <= m ?
   │
   ├── না → বাইরের লুপে ফিরে যাও
   │
   └── হ্যাঁ
         │
         ▼
   j % 11 == 0 ?
         │
     ┌───┴────┐
     │        │
    হ্যাঁ     না
     │        │
continue   printf(j)
     │        │
     └───► j++ ◄───┘
            │
            ▼
        আবার j <= m
*/
